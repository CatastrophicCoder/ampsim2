"""Block registry: which testbench, input source, output node and probes belong to each block id
(SPEC §4.2, VERIFICATION §1). Testbenches are generated by harness/testbench_gen.py."""
import re
from dataclasses import dataclass, field

from . import config, netlist

# DC reference nodes of the full netlist (CIRCUIT.md §5)
FULL_DC_NODES = ('ct', 'nscr', 'bpx', 'bpa', 'nbias', 'p1a', 'k1a', 'p1b', 'k1b', 'p2a', 'k2a', 'k2b',
                 'p3a', 'p3b', 'k3', 'nf', 'ng')
# testbench-only helper nodes (junction source terminals) that F does not have
HELPER_NODES = ('j2s', 'j3s', 'j4s', 'j5a', 'j5b')


@dataclass(frozen=True)
class Block:
    id: str
    title: str
    testbench: str                # file in harness/testbenches/
    input_node: str | None        # node of the `Vin` source (None: inputs are recordings only)
    output_node: str              # node compared against the engine's 'out'
    probes: tuple = ()            # extra nodes rendered for overlays / debugging
    dc_nodes: tuple | None = None  # nodes in the DC tables; None = every testbench node that F has
    levels: dict = field(default_factory=dict)   # VERIFICATION §4, volts peak at the input source
    engine_block: str = ''        # ampwav --block id
    output_load: float = 0.0      # ohms, for power metrics (0 = none)
    recorded: tuple = ()          # Vrec_<name> sources: need recordings from another run (M4)
    linear: bool = False          # scored with the linear-block tolerances (VERIFICATION §7)

    @property
    def path(self):
        return config.TESTBENCH_DIR / self.testbench

    def dc_node_list(self):
        """DC table nodes: the given list, or every testbench node that F has, without the nodes that a
        recorded source drives directly (e.g. the speaker voltage `out` in b5open: an input there)."""
        if self.dc_nodes is not None:
            return list(self.dc_nodes)
        text = self.path.read_text()
        driven = {m.group(1).lower() for m in re.finditer(r'^Vrec_\w+\s+(\S+)\s+0\b', text, re.I | re.M)}
        nodes = netlist.parse(text).nodes()
        return [n for n in nodes if n not in HELPER_NODES and n not in driven]



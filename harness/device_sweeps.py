"""Device DC sweep tables for the engine's device unit tests (VERIFICATION §5.1, WDF_DESIGN §3.3).
Single-tube ngspice testbenches with ideal voltage sources on every electrode (cathode at ground) and
tight DC tolerances. Writes tests/data/{12ax7,el34}_{plate,grid}.csv; the files are committed.

    python -m harness.device_sweeps          # regenerate
    python -m harness.device_sweeps --check  # exit 1 if a committed table is out of date

Columns (SI units): electrode voltages vs cathode, then for each current the device value the engine
model must reproduce (`ip`, `is`, `ig`; WDF_DESIGN §3 omits the 1 GΩ Rcp of tubes.lib, so
ip = ip_terminal − Vpk / 1 GΩ) and the SPICE terminal plate current `ip_terminal`. Currents flow into
the electrode (plate, screen, grid) and out of the cathode.
"""
import argparse
import hashlib
import sys

import numpy as np

from . import config, spice

DATA_DIR = config.ROOT / 'tests' / 'data'
RCP = 1e9                                        # tubes.lib Rcp (plate-cathode), omitted in the engine
OPTIONS = '.options reltol=1e-12 abstol=1e-18 vntol=1e-12 gmin=1e-18'

TRIODE_VGK = (0.0, -0.5, -1.0, -1.5, -2.0, -3.0, -4.0)
TRIODE_GRID_VGK = (-1.0, -0.5, 0.0, 0.25, 0.5, 1.0, 2.0, 5.0)
TRIODE_GRID_VPK = 200.0
PENTODE_VSK = (250.0, 400.0, 490.0)
PENTODE_VGK = (0.0, -10.0, -20.0, -30.0, -40.0, -46.0, -50.0, -60.0)
PENTODE_GRID_VGK = (-5.0, 0.0, 1.0, 5.0, 10.0)
PENTODE_GRID_VPK = PENTODE_GRID_VSK = 400.0      # VERIFICATION §5.1 leaves these open (D-019)


def _sweep(tube, fixed, sweep_src, start, stop, step):
    """One ngspice DC sweep. `fixed`: {source: volts}. Returns {source: current into the electrode}."""
    pins = {'12AX7': 'p g 0', 'EL34': 'p s g 0'}[tube]
    srcs = {'Vp': 'p', 'Vg': 'g', **({'Vs': 's'} if tube == 'EL34' else {})}
    lines = [f'* {tube} DC sweep', f'.include {config.TUBES}', OPTIONS]
    lines += [f'{name} {node} 0 DC {fixed.get(name, 0.0)!r}' for name, node in srcs.items()]
    lines.append(f'X1 {pins} {tube}')
    _, raws = spice._run('\n'.join(lines) + '\n', f'dc {sweep_src} {start!r} {stop!r} {step!r}\nwrite dc.raw all')
    raw = raws['dc.raw']
    # a source's branch current flows from + through the source, i.e. out of the electrode: negate
    return {name: -raw[f'i({name.lower()})'].real for name in srcs}, raw[f'v({srcs[sweep_src]})'].real


def triode_plate():
    rows = []
    for vg in TRIODE_VGK:
        i, vp = _sweep('12AX7', {'Vg': vg}, 'Vp', 0.0, 400.0, 5.0)
        rows += [(vg, p, ipt - p / RCP, ig, ipt) for p, ipt, ig in zip(vp, i['Vp'], i['Vg'])]
    return ('vgk', 'vpk', 'ip', 'ig', 'ip_terminal'), rows


def triode_grid():
    rows = []
    for vg in TRIODE_GRID_VGK:
        i, vp = _sweep('12AX7', {'Vg': vg}, 'Vp', TRIODE_GRID_VPK, TRIODE_GRID_VPK, 1.0)
        rows += [(vg, p, ipt - p / RCP, ig, ipt) for p, ipt, ig in zip(vp, i['Vp'], i['Vg'])]
    return ('vgk', 'vpk', 'ip', 'ig', 'ip_terminal'), rows


def pentode_plate():
    rows = []
    for vs in PENTODE_VSK:
        for vg in PENTODE_VGK:
            i, vp = _sweep('EL34', {'Vg': vg, 'Vs': vs}, 'Vp', 0.0, 600.0, 10.0)
            rows += [(vs, vg, p, ipt - p / RCP, is_, ig, ipt)
                     for p, ipt, is_, ig in zip(vp, i['Vp'], i['Vs'], i['Vg'])]
    return ('vsk', 'vgk', 'vpk', 'ip', 'is', 'ig', 'ip_terminal'), rows


def pentode_grid():
    rows = []
    for vg in PENTODE_GRID_VGK:
        i, vp = _sweep('EL34', {'Vg': vg, 'Vs': PENTODE_GRID_VSK}, 'Vp', PENTODE_GRID_VPK, PENTODE_GRID_VPK, 1.0)
        rows += [(PENTODE_GRID_VSK, vg, p, ipt - p / RCP, is_, ig, ipt)
                 for p, ipt, is_, ig in zip(vp, i['Vp'], i['Vs'], i['Vg'])]
    return ('vsk', 'vgk', 'vpk', 'ip', 'is', 'ig', 'ip_terminal'), rows


TABLES = {
    '12ax7_plate.csv': (triode_plate, '12AX7 plate curves: Vpk 0–400 V (5 V) for each Vgk'),
    '12ax7_grid.csv': (triode_grid, f'12AX7 grid current at Vpk = {TRIODE_GRID_VPK:g} V'),
    'el34_plate.csv': (pentode_plate, 'EL34 plate curves: Vpk 0–600 V (10 V) for each Vsk and Vgk'),
    'el34_grid.csv': (pentode_grid, f'EL34 grid current at Vpk = Vsk = {PENTODE_GRID_VPK:g} V'),
}


def render(name):
    fn, title = TABLES[name]
    cols, rows = fn()
    sha = hashlib.sha256(config.TUBES.read_bytes()).hexdigest()[:16]
    head = [f'# {title}', '# GENERATED by harness/device_sweeps.py (VERIFICATION §5.1), do not edit',
            f'# source: reference/spice/tubes.lib (sha256 {sha}), ngspice {spice.ngspice_version()}',
            '# ip = device plate current without the 1 GOhm Rcp (engine model); ip_terminal = SPICE terminal',
            '# currents in A into plate / screen / grid; voltages in V vs cathode', ','.join(cols)]
    body = [','.join(f'{v + 0.0:.15g}' for v in r) for r in rows]   # + 0.0: no '-0'
    return '\n'.join(head + body) + '\n'


def read(name):
    """Returns {column: array} of a committed table."""
    path = DATA_DIR / name
    lines = [ln for ln in path.read_text().splitlines() if not ln.startswith('#')]
    cols = lines[0].split(',')
    data = np.array([[float(x) for x in ln.split(',')] for ln in lines[1:]])
    return {c: data[:, k] for k, c in enumerate(cols)}


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument('--check', action='store_true')
    a = ap.parse_args()
    DATA_DIR.mkdir(parents=True, exist_ok=True)
    stale = []
    for name in TABLES:
        text, path = render(name), DATA_DIR / name
        if a.check:
            if not path.exists() or path.read_text() != text:
                stale.append(name)
        else:
            path.write_text(text)
            print(f'wrote {path.relative_to(config.ROOT)} ({text.count(chr(10)) - 6} rows)')
    if stale:
        print('out of date: ' + ', '.join(stale) + ' (run python -m harness.device_sweeps)')
        sys.exit(1)


if __name__ == '__main__':
    main()

"""SPICE fixtures for the output transformer network alone (CIRCUIT.md §3: "verify with a small-signal
comparison of the transformer network alone (plates driven by ideal current sources, SPICE vs engine)").

The transformer lines of the reference netlist with the 16 Ω load, the centre tap at 0 V (AC ground),
and the plates driven by ideal current sources from a control voltage `vinn` (1 A per volt):
- `diff`: i into pA and out of pB (push-pull),
- `single`: i into pA only (common-mode content, leakage and the other half-primary).
1 GΩ resistors give the plates a DC path in SPICE and in the engine alike. Writes
tests/data/ot_ac.csv (AC: v(out), v(pA), v(pB) per 1 A) and tests/data/ot_tran.csv (transient on the
768 kHz grid, `diff` drive: 100 Hz + 3 kHz + 15 kHz, 20 mA each, 5 ms, 0.5 ms raised-cosine fade-in).

    python -m harness.ot_fixtures [--check]
"""
import argparse
import sys

import numpy as np

from . import config, ot_fit, spice

DRIVES = {'diff': 'Gdrv_a 0 pA vinn 0 1\nGdrv_b pB 0 vinn 0 1\n', 'single': 'Gdrv_a 0 pA vinn 0 1\n'}
TRAN_FREQS = (100.0, 3000.0, 15000.0)
TRAN_AMP = 0.02
TRAN_SECONDS = 0.005
NODES = ('out', 'pa', 'pb')


def testbench(drive):
    ot = ot_fit.netlist_ot_text().replace('Rct ct 0 1G\n', '')
    return (f'* OT network alone, {drive} drive (harness/ot_fixtures.py)\n' + ot
            + 'Rload out 0 16\nVct ct 0 DC 0\nRbig_a pA 0 1G\nRbig_b pB 0 1G\n'
            + 'Vin vinn 0 DC 0 AC 1\n' + DRIVES[drive])


TRAN_FADE = 0.0005


def tran_input():
    """The multi-sine with a raised-cosine fade-in over TRAN_FADE s: an input that starts with a nonzero
    di/dt is inconsistent with the zero initial state (v_L = L·di/dt jumps), and the trapezoidal rule
    answers with an undamped alternation at the plates, which SPICE's start-up step does not show."""
    t = np.arange(int(round(TRAN_SECONDS * config.FS))) / config.FS
    fade = np.where(t < TRAN_FADE, 0.5 - 0.5 * np.cos(np.pi * t / TRAN_FADE), 1.0)
    return fade * sum(TRAN_AMP * np.sin(2 * np.pi * f * t) for f in TRAN_FREQS)


def generate():
    lines = ['# OT network alone: AC response per 1 A of drive current (CIRCUIT.md §3)',
             '# GENERATED by harness/ot_fixtures.py, do not edit',
             f'# ngspice {spice.ngspice_version()}; drives: diff = into pA and out of pB, single = into pA',
             'drive,f,re_out,im_out,re_pa,im_pa,re_pb,im_pb']
    for drive in DRIVES:
        tb = testbench(drive)
        f, h = {}, {}
        for n in NODES:
            f[n], h[n] = spice.ac(tb, {}, n, 'vinn', fstart=10.0, fstop=40000.0, ppd=10)
        for k, fk in enumerate(f['out']):
            lines.append(f'{drive},{fk:.17g},' + ','.join(f'{h[n][k].real:.17g},{h[n][k].imag:.17g}' for n in NODES))
    ac = '\n'.join(lines) + '\n'
    x = tran_input()
    res = spice.tran(testbench('diff'), {}, x, list(NODES))
    lines = ['# OT network alone: transient, diff drive, 768 kHz grid (CIRCUIT.md §3)',
             '# GENERATED by harness/ot_fixtures.py, do not edit',
             f'# ngspice {spice.ngspice_version()}, reltol {config.SPICE_RELTOL}; fs {config.FS} Hz; '
             f'i = sum of {", ".join(f"{f:g} Hz" for f in TRAN_FREQS)} at {TRAN_AMP} A, {TRAN_FADE * 1e3:g} ms fade-in',
             'i,out,pa,pb']
    lines += [f'{a:.17g},{b:.17g},{c:.17g},{d:.17g}' for a, b, c, d in zip(x, res['out'], res['pa'], res['pb'])]
    return {'ot_ac.csv': ac, 'ot_tran.csv': '\n'.join(lines) + '\n'}


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument('--check', action='store_true')
    a = ap.parse_args()
    data = config.ROOT / 'tests' / 'data'
    stale = []
    for name, text in generate().items():
        path = data / name
        if a.check:
            if not path.exists() or path.read_text() != text:
                stale.append(name)
        else:
            path.write_text(text)
            print(f'ot_fixtures: wrote {path.relative_to(config.ROOT)}')
    if stale:
        print('out of date: ' + ', '.join(stale))
        sys.exit(1)


if __name__ == '__main__':
    main()
